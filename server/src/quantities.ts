/**
 * کالاهای وزنی تا سه رقم اعشار معتبرند (DTO: maxDecimalPlaces 3). جمع و
 * تفریق ممیز شناور بدون گردکردن از مقدار واقعی منحرف می‌شود (۰٫۱ + ۰٫۲ =
 * ۰٫۳۰۰۰…۴) و دو مشکل واقعی می‌سازد:
 *   ۱) مقایسه‌های آستانه به‌اشتباه رد می‌شوند — فروشِ «آخرین ۰٫۳ کیلو» وقتی
 *      قفسه دقیقاً ۰٫۳ دارد با «موجودی کافی نیست» شکست می‌خورد؛
 *   ۲) مقدار ذخیره‌شدهٔ موجودی قدم‌به‌قدم آلوده می‌شود و سال‌ها بعد همان
 *      باگ مرزی را دوباره تولید می‌کند.
 * هر جمع/تفریق/ضرب کمیتی سمت سرور باید از این گردکننده رد شود؛ نوشتنِ
 * نهایی هم (در SQL) با ROUND(…, 3) نرمال می‌شود تا خطای قدیمی هم التیام یابد.
 */
export const roundQty = (value: number): number => Math.round(value * 1000) / 1000;
